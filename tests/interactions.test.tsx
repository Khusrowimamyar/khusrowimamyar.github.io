import { afterEach, beforeEach, expect, test, vi } from 'vitest';
import { act, cleanup, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { ProjectGrid } from '@/components/project-grid';
import { Navigation } from '@/components/navigation';
vi.mock('next/link',()=>({default:({children,href,...props}:{children:React.ReactNode;href:string})=><a href={href} {...props}>{children}</a>}));
beforeEach(()=>{localStorage.clear();document.documentElement.dataset.theme='light';vi.stubGlobal('IntersectionObserver',class{observe(){}unobserve(){}disconnect(){}});});
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
test('delayed theme initialization preserves a theme chosen immediately after mount',async()=>{
 let initialize: FrameRequestCallback | undefined;
 vi.stubGlobal('requestAnimationFrame',(callback:FrameRequestCallback)=>{initialize=callback;return 1;});
 vi.stubGlobal('cancelAnimationFrame',vi.fn());
 const user=userEvent.setup();render(<Navigation/>);
 await user.click(screen.getByRole('button',{name:'Switch to dark theme'}));
 act(()=>initialize?.(0));
 expect(document.documentElement.dataset.theme).toBe('dark');
 await user.click(screen.getByRole('button',{name:'Switch to light theme'}));
 expect(document.documentElement.dataset.theme).toBe('light');
 expect(localStorage.getItem('theme')).toBe('light');
});
test('project filters expose the expanded résumé work and reset to all projects',async()=>{
 const user=userEvent.setup();render(<ProjectGrid/>);
 expect(screen.getAllByRole('article')).toHaveLength(10);
 expect(screen.getByRole('button',{name:'All work 10'})).toBeTruthy();
 expect(screen.getByRole('link',{name:'Read pTron case study'}).getAttribute('href')).toBe('/projects/ptron/');
 await user.click(screen.getByRole('button',{name:'AI & automation 02'}));
 expect(screen.getAllByRole('article')).toHaveLength(2);
 expect(screen.getByRole('heading',{name:'WriteGenius.ai'})).toBeTruthy();
 expect(screen.getByRole('heading',{name:'Python Workflow Automation'})).toBeTruthy();
 expect(screen.queryByRole('heading',{name:'GrabCash'})).toBeNull();
 await user.click(screen.getByRole('button',{name:'Web & CMS 04'}));
 expect(screen.getAllByRole('article')).toHaveLength(4);
 for(const name of ['YardBell','pTron','Shan-e-Tajalli','WordPress Publications'])expect(screen.getByRole('heading',{name})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'UI/UX 01'}));
 expect(screen.getAllByRole('article')).toHaveLength(1);
 expect(screen.getByRole('heading',{name:'Freelance UI/UX'})).toBeTruthy();
 expect(screen.getByRole('status').textContent).toBe('Showing 1 of 10 projects');
 await user.click(screen.getByRole('button',{name:'Full stack 03'}));
 expect(screen.getAllByRole('article')).toHaveLength(3);
 expect(screen.getByRole('heading',{name:'GrabOn.com / GrabOn.ca'})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'All work 10'}));
 expect(screen.getAllByRole('article')).toHaveLength(10);
 expect(screen.getByRole('status').textContent).toBe('Showing 10 of 10 projects');
});
test('theme toggle updates page theme, accessible label, and saved preference',async()=>{const user=userEvent.setup();render(<Navigation/>);await user.click(screen.getByRole('button',{name:'Switch to dark theme'}));expect(document.documentElement.dataset.theme).toBe('dark');expect(localStorage.getItem('theme')).toBe('dark');await user.click(screen.getByRole('button',{name:'Switch to light theme'}));expect(document.documentElement.dataset.theme).toBe('light');expect(localStorage.getItem('theme')).toBe('light');});
test('mobile navigation closes with Escape and after choosing a section',async()=>{const user=userEvent.setup();render(<Navigation/>);await user.click(screen.getByRole('button',{name:'Open navigation'}));expect(screen.getByRole('button',{name:'Close navigation'}).getAttribute('aria-expanded')).toBe('true');await user.keyboard('{Escape}');expect(screen.getByRole('button',{name:'Open navigation'}).getAttribute('aria-expanded')).toBe('false');await user.click(screen.getByRole('button',{name:'Open navigation'}));await user.click(screen.getByRole('link',{name:'Projects'}));await waitFor(()=>expect(screen.getByRole('button',{name:'Open navigation'}).getAttribute('aria-expanded')).toBe('false'));expect(screen.getByRole('link',{name:'Projects'}).getAttribute('href')).toBe('/#projects');});
